def get_series_name(categ_name):
    """Extract series name from category path like '功能系列 / 迷你香' -> '功能系列'."""
    if "/" in categ_name:
        return categ_name.split("/")[0].strip()
    return categ_name


def get_product_description(product_name):
    """Match product name to description using substring matching."""
    # Strip "迷你香 – " prefix to get the core name
    core_name = product_name.replace("迷你香 – ", "").replace("迷你香 - ", "")
    
    # Try exact match first
    if core_name in PRODUCT_DESCRIPTIONS:
        return PRODUCT_DESCRIPTIONS[core_name]
    
    # Try substring match
    for key, desc in PRODUCT_DESCRIPTIONS.items():
        if key in core_name or core_name in key:
            return desc
    
    return None


